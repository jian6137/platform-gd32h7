{
    volatile uint16_t *frame = (volatile uint16_t *)DISPLAY_FRAMEBUFFER;
    memmove((void *)frame, (const void *)(frame + (16U * LCD_WIDTH)),
            (16U * (LCD_CONSOLE_ROWS - 1U) * LCD_WIDTH * sizeof(uint16_t)));

    uint32_t start_idx = 16U * (LCD_CONSOLE_ROWS - 1U) * LCD_WIDTH;
    uint32_t end_idx = LCD_WIDTH * LCD_HEIGHT;
    for (uint32_t i = start_idx; i < end_idx; ++i) {
        frame[i] = s_bg_color;
    }
    s_cursor_y = LCD_CONSOLE_ROWS - 1U;
}

void lcd_console_putc(char c)
{
    usart_send_char(c);

    if (c == '\r') {
        s_cursor_x = 0U;
        return;
    }
    if (c == '\n') {
        s_cursor_x = 0U;
        s_cursor_y++;
        if (s_cursor_y >= LCD_CONSOLE_ROWS) {
            console_scroll_up();
        }
        return;
    }
    if (c == '\t') {
        s_cursor_x = (s_cursor_x + 4U) & ~3U;
        if (s_cursor_x >= LCD_CONSOLE_COLS) {
            s_cursor_x = 0U;
            s_cursor_y++;
            if (s_cursor_y >= LCD_CONSOLE_ROWS) {
                console_scroll_up();
            }
        }
        return;
    }

    draw_char_bitmap(s_cursor_x, s_cursor_y, c, s_fg_color, s_bg_color);
    s_cursor_x++;
    if (s_cursor_x >= LCD_CONSOLE_COLS) {
        s_cursor_x = 0U;
        s_cursor_y++;
        if (s_cursor_y >= LCD_CONSOLE_ROWS) {
            console_scroll_up();
        }
    }
}

void lcd_console_print(const char *str)
{
    if (str == NULL) {
        return;
    }
    while (*str) {
        lcd_console_putc(*str++);
    }
    lcd_console_flush();
}

void lcd_console_printf(const char *fmt, ...)
{
    char buf[256];
    va_list args;

    va_start(args, fmt);
    vsnprintf(buf, sizeof(buf), fmt, args);
    va_end(args);

    lcd_console_print(buf);
}

void lcd_console_flush(void)
{
    SCB_CleanDCache_by_Addr((volatile void *)DISPLAY_FRAMEBUFFER, (int32_t)LCD_FRAME_BYTES);
    tli_reload_config(TLI_REQUEST_RELOAD_EN);
}

void lcd_draw_string_xy(uint16_t px, uint16_t py, const char *str, uint16_t fg, uint16_t bg)
{
    if (str == NULL) {
        return;
    }
    volatile uint16_t *frame = (volatile uint16_t *)DISPLAY_FRAMEBUFFER;
    while (*str) {
        char c = *str++;
        if ((unsigned char)c < 32U || (unsigned char)c > 126U) {
            c = ' ';
        }
        uint32_t font_idx = ((uint32_t)c - 32U) * 16U;
        for (uint32_t y = 0U; y < 16U; ++y) {
            if ((py + y) >= LCD_HEIGHT) {
                break;
            }
            uint16_t line_bits = ASCII8x16_Table[font_idx + y];
            uint32_t fb_offset = (py + y) * LCD_WIDTH + px;
            for (uint32_t x = 0U; x < 8U; ++x) {
                if ((px + x) >= LCD_WIDTH) {
                    break;
                }
                frame[fb_offset + x] = (line_bits & (0x80U >> x)) ? fg : bg;
            }
        }
        px += 8U;
        if (px >= LCD_WIDTH) {
            break;
        }
    }
}

