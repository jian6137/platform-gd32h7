void lcd_draw_volume_osd(uint8_t volume_percent)
{
    const uint32_t osd_w = 176U;
    const uint32_t osd_h = 56U;
    const uint32_t osd_x = (LCD_WIDTH - osd_w) / 2U;
    const uint32_t osd_y = (LCD_HEIGHT - osd_h) / 2U;
    const int r = 8;
    const int r2 = r * r;
    const int r_in2 = (r - 2) * (r - 2);
    const uint16_t osd_bg = 0x10A2U;
    const uint16_t osd_border = CONSOLE_COLOR_CYAN;

    volatile uint16_t *frame = (volatile uint16_t *)DISPLAY_FRAMEBUFFER;
    uint32_t x, y;

    for (y = 0U; y < osd_h; ++y) {
        uint32_t screen_y = osd_y + y;
        uint32_t row_offset = screen_y * LCD_WIDTH;

        for (x = 0U; x < osd_w; ++x) {
            uint32_t screen_x = osd_x + x;
            int dx = 0;
            int dy = 0;
            bool is_corner = false;

            if (x < (uint32_t)r && y < (uint32_t)r) {
                dx = (int)((uint32_t)r - 1U - x);
                dy = (int)((uint32_t)r - 1U - y);
                is_corner = true;
            } else if (x >= (osd_w - (uint32_t)r) && y < (uint32_t)r) {
                dx = (int)(x - (osd_w - (uint32_t)r));
                dy = (int)((uint32_t)r - 1U - y);
                is_corner = true;
            } else if (x < (uint32_t)r && y >= (osd_h - (uint32_t)r)) {
                dx = (int)((uint32_t)r - 1U - x);
                dy = (int)(y - (osd_h - (uint32_t)r));
                is_corner = true;
            } else if (x >= (osd_w - (uint32_t)r) && y >= (osd_h - (uint32_t)r)) {
                dx = (int)(x - (osd_w - (uint32_t)r));
                dy = (int)(y - (osd_h - (uint32_t)r));
                is_corner = true;
            }

            if (is_corner) {
                int dist2 = dx * dx + dy * dy;
                if (dist2 <= r2) {
                    frame[row_offset + screen_x] = (dist2 >= r_in2) ? osd_border : osd_bg;
                }
            } else {
                bool is_edge = (x < 2U || x >= (osd_w - 2U) || y < 2U || y >= (osd_h - 2U));
                frame[row_offset + screen_x] = is_edge ? osd_border : osd_bg;
            }
        }
    }

    const uint32_t icon_x = osd_x + 14U;
    const uint32_t icon_y = osd_y + 10U;
    const uint16_t icon_color = (volume_percent > 0U) ? CONSOLE_COLOR_GREEN : CONSOLE_COLOR_RED;
    const uint16_t *icon_data = (volume_percent > 0U) ? s_speaker_icon_16x16 : s_mute_icon_16x16;

    for (y = 0U; y < 16U; ++y) {
        uint16_t bits = icon_data[y];
        uint32_t fb_row = (icon_y + y) * LCD_WIDTH + icon_x;
        for (x = 0U; x < 16U; ++x) {
            if (bits & (0x8000U >> x)) {
                frame[fb_row + x] = icon_color;
            }
        }
    }

    char vol_str[16];
    if (volume_percent == 0U) {
        snprintf(vol_str, sizeof(vol_str), "VOL:  0%% [MUTE]");
    } else {
        snprintf(vol_str, sizeof(vol_str), "VOL: %3u%%", (unsigned int)volume_percent);
    }
    lcd_draw_string_xy(osd_x + 36U, osd_y + 10U, vol_str, CONSOLE_COLOR_WHITE, osd_bg);

    const uint32_t bar_x = osd_x + 14U;
    const uint32_t bar_y = osd_y + 34U;
    const uint32_t bar_w = 148U;
    const uint32_t bar_h = 10U;
    const uint32_t bar_fill = (bar_w * (uint32_t)volume_percent) / 100U;

    for (x = 0U; x < bar_w + 2U; ++x) {
        frame[(bar_y - 1U) * LCD_WIDTH + (bar_x - 1U + x)] = CONSOLE_COLOR_LIGHTGRAY;
        frame[(bar_y + bar_h) * LCD_WIDTH + (bar_x - 1U + x)] = CONSOLE_COLOR_LIGHTGRAY;
    }
    for (y = 0U; y < bar_h; ++y) {
        frame[(bar_y + y) * LCD_WIDTH + (bar_x - 1U)] = CONSOLE_COLOR_LIGHTGRAY;
        frame[(bar_y + y) * LCD_WIDTH + (bar_x + bar_w)] = CONSOLE_COLOR_LIGHTGRAY;
    }

    for (y = 0U; y < bar_h; ++y) {
        uint32_t fb_bar_row = (bar_y + y) * LCD_WIDTH + bar_x;
        for (x = 0U; x < bar_w; ++x) {
            if (x < bar_fill) {
                frame[fb_bar_row + x] = (volume_percent > 0U) ? CONSOLE_COLOR_GREEN : CONSOLE_COLOR_RED;
            } else {
                frame[fb_bar_row + x] = 0x2104U;
            }
        }
    }
}

