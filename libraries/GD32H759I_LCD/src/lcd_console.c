static void usart_debug_init(void)
{
    if (s_usart_initialized) {
        return;
    }
    rcu_periph_clock_enable(RCU_GPIOA);
    rcu_periph_clock_enable(RCU_USART0);

    gpio_af_set(GPIOA, GPIO_AF_7, GPIO_PIN_9 | GPIO_PIN_10);
    gpio_mode_set(GPIOA, GPIO_MODE_AF, GPIO_PUPD_PULLUP, GPIO_PIN_9 | GPIO_PIN_10);
    gpio_output_options_set(GPIOA, GPIO_OTYPE_PP, GPIO_OSPEED_100_220MHZ, GPIO_PIN_9 | GPIO_PIN_10);

    usart_deinit(USART0);
    usart_baudrate_set(USART0, 115200U);
    usart_receive_config(USART0, USART_RECEIVE_ENABLE);
    usart_transmit_config(USART0, USART_TRANSMIT_ENABLE);
    usart_enable(USART0);

    s_usart_initialized = 1U;
}

static void usart_send_char(char c)
{
    if (!s_usart_initialized) {
        usart_debug_init();
    }
    if (c == '\n') {
        usart_data_transmit(USART0, (uint8_t)'\r');
        while (RESET == usart_flag_get(USART0, USART_FLAG_TBE)) {}
    }
    usart_data_transmit(USART0, (uint8_t)c);
    while (RESET == usart_flag_get(USART0, USART_FLAG_TBE)) {}
}

