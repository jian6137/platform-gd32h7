void lcd_console_clear(void)
{
    volatile uint16_t *frame = (volatile uint16_t *)DISPLAY_FRAMEBUFFER;
    for (uint32_t i = 0U; i < (LCD_WIDTH * LCD_HEIGHT); ++i) {
        frame[i] = s_bg_color;
    }
    s_cursor_x = 0U;
    s_cursor_y = 0U;
    lcd_console_flush();
}

static void draw_char_bitmap(uint16_t col, uint16_t row, char c, uint16_t fg, uint16_t bg)
{
    volatile uint16_t *frame = (volatile uint16_t *)DISPLAY_FRAMEBUFFER;
    uint16_t px = col * 8U;
    uint16_t py = row * 16U;

    if ((unsigned char)c < 32U || (unsigned char)c > 126U) {
        c = ' ';
    }
    uint32_t font_idx = ((uint32_t)c - 32U) * 16U;

    for (uint32_t y = 0U; y < 16U; ++y) {
        uint16_t line_bits = ASCII8x16_Table[font_idx + y];
        uint32_t fb_offset = (py + y) * LCD_WIDTH + px;
        for (uint32_t x = 0U; x < 8U; ++x) {
            frame[fb_offset + x] = (line_bits & (0x80U >> x)) ? fg : bg;
        }
    }
}

